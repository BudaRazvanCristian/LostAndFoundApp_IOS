#!/usr/bin/env node

/**
 * get-local-ip.js - Detectează automat IP-ul local al mașinii
 * Uso: node scripts/get-local-ip.js
 */

const os = require('os');
const path = require('path');
const fs = require('fs');

function getLocalIP() {
  const interfaces = os.networkInterfaces();

  // Preferință: en0 (macOS), eth0/wlan0 (Linux), Ethernet (Windows)
  const preferredInterfaces = ['en0', 'eth0', 'wlan0', 'wi-fi', 'Wi-Fi', 'Ethernet'];

  for (const iface of preferredInterfaces) {
    if (interfaces[iface]) {
      for (const addr of interfaces[iface]) {
        if (addr.family === 'IPv4' && !addr.internal) {
          return addr.address;
        }
      }
    }
  }

  // Fallback: orice IPv4 non-internal
  for (const name of Object.keys(interfaces)) {
    for (const addr of interfaces[name]) {
      if (addr.family === 'IPv4' && !addr.internal) {
        return addr.address;
      }
    }
  }

  return 'localhost';
}

const localIP = getLocalIP();
console.log(localIP);

// Scrie IP-ul și într-un fișier .env local pentru referință
const envFile = path.join(__dirname, '..', '.env.local');
const generatedHostFile = path.join(__dirname, '..', 'src', 'config', 'generatedLocalHost.ts');
try {
  const envContent = fs.readFileSync(envFile, 'utf-8') || '';
  const envLines = envContent.split('\n').filter(line => !line.startsWith('EXPO_PUBLIC_API_HOST='));
  envLines.push(`EXPO_PUBLIC_API_HOST=${localIP}`);
  fs.writeFileSync(envFile, envLines.filter(l => l.trim()).join('\n') + '\n');
  console.error(`✅ Updated .env.local with LOCAL_IP=${localIP}`);
} catch (e) {
  console.error(`⚠️  Could not update .env.local: ${e.message}`);
}

try {
  const generatedContent = [
    '// Auto-generated by scripts/get-local-ip.js',
    `export const GENERATED_LOCAL_API_HOST = '${localIP}';`,
    '',
  ].join('\n');
  fs.writeFileSync(generatedHostFile, generatedContent);
  console.error(`✅ Updated src/config/generatedLocalHost.ts with LOCAL_IP=${localIP}`);
} catch (e) {
  console.error(`⚠️  Could not update generatedLocalHost.ts: ${e.message}`);
}

